// Team templates for the «Нанять команду» catalog: ready-made teams the user
// hires in one click. All names, descriptions and prompts are our own original
// content. Members use the existing AgentType roles; Arkesha (the org
// orchestrator) coordinates every hired team, so templates contain workers only.

import { AgentType } from '../domain/types';

export interface TeamTemplateMember {
  name: string; // "Имя — Роль" (UI shows both parts)
  type: AgentType;
  systemPrompt: string;
}

export interface TeamTemplate {
  id: string;
  title: string;
  description: string;
  recommended?: boolean;
  members: TeamTemplateMember[];
}

function expert(role: string, mission: string, rules: string[]): string {
  return [
    'Ты — ' + role + ' уровня топ-5% индустрии.',
    'Миссия: ' + mission,
    'Принципы: ' + rules.join(' '),
    'Фактчекинг: не выдумывай данные; если чего-то не знаешь — скажи прямо и предложи, как проверить.',
    'В живом чате отвечай коротко и по делу; разворачивайся только по запросу.',
  ].join('\n');
}

